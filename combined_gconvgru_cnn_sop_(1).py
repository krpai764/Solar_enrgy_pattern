gcn_output_dim=10

class CombinedModel(nn.Module):
    def __init__(self, gcn_input_dim, gcn_hidden_dim, gcn_output_dim):
        super(CombinedModel, self).__init__()
        self.gcn_model = GCN(gcn_input_dim, gcn_hidden_dim, gcn_output_dim)
        self.cnn_model = ConvNet()
        self.fc=nn.Linear(60,10)
        self.fc2=nn.Linear(10,1)

    def forward(self, x_gcn, edge_index, x_cnn):
        output_gcn = self.gcn_model(x_gcn, edge_index)
        output_cnn = self.cnn_model(x_cnn)
        output_cnn=torch.flatten(output_cnn)
        output_gcn=torch.flatten(output_gcn)
        z=torch.cat((output_gcn,output_cnn),axis=0)
        z=self.fc(z)
        z=F.relu(z)
        z=self.fc2(z)
        return z

