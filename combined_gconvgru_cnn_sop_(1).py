import torch
import torch.nn as nn
import torch.nn.functional as F
from torch_geometric_temporal.nn.recurrent import GConvGRU

class GCN(nn.Module):
    def __init__(self, input_dim, hidden_dim, output_dim):
        super(GCN, self).__init__()
        self.conv1 = GConvGRU(input_dim, hidden_dim, K=2)
        self.conv2=GConvGRU(hidden_dim,hidden_dim,K=2)
        self.fc = nn.Linear(hidden_dim, output_dim)

    def forward(self, x, edge_index):
        x = self.conv1(x, edge_index)
        x = F.relu(x)
        x=self.conv2(x,edge_index)
        x=F.tanh(x)
        x = self.fc(x)
        return x

class ConvNet(nn.Module):
    def __init__(self):
        super(ConvNet, self).__init__()
        # First convolutional layer with 128 kernels of size 3x3
        self.conv1 = nn.Conv2d(in_channels=1, out_channels=128, kernel_size=3, stride=1, padding=1)
        # Second convolutional layer with 64 kernels of size 3x3
        self.conv2 = nn.Conv2d(in_channels=128, out_channels=64, kernel_size=3, stride=1, padding=1)
        # Activation function
        self.relu = nn.ReLU()
        # Max pooling layer
        self.pool = nn.MaxPool2d(kernel_size=2, stride=2)
        # Fully connected layer
        self.fc = nn.Linear(128, 10)  # Input size depends on the spatial dimensions of the output from the previous layer

    def forward(self, x):
        # Forward pass through the first convolutional layer
       #
        x = self.conv1(x)
        x = self.relu(x)
        x = self.pool(x)
        # Forward pass through the second convolutional layer
        x = self.conv2(x)
        x = self.relu(x)
        x = self.pool(x)
        # Flatten the output from the convolutional layers
        x = x.view(-1, 128)
        # Forward pass through the fully connected layer
        x = self.fc(x)
        return x

gcn_input_dim=10
